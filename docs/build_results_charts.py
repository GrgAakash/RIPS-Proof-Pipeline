def table_rows(text: str) -> list[list[str]]:
    return [
        [cell.strip() for cell in re.split(r"(?<!\\)\|", line)[1:-1]]
        for line in text.splitlines() if line.startswith("| ")
    ]


def benchmark_data(root: Path = ROOT) -> list[list[str]]:
    rows = [row for row in table_rows((root / "Results/README.md").read_text())
            if row[0].startswith(("ArXivMath ", "BrokenArXiv "))]
    if len(rows) != 2:
        raise ValueError("Expected two benchmark rows")
    for _, direct, pipeline, difference in rows:
        a, b = Decimal(direct.rstrip("%")), Decimal(pipeline.rstrip("%"))
        if not (0 <= a <= 100 and 0 <= b <= 100):
            raise ValueError("Benchmark scores must be percentages in [0, 100]")
        if b - a != Decimal(difference.split()[0]):
            raise ValueError("Benchmark difference disagrees with reported scores")
    return rows


def paper_data(root: Path = ROOT) -> list[tuple[str, int, int, int]]:
    result = []
    for label, name in (("With context", "report.md"),
                        ("Without context", "report_without_lemma.md")):
        text = (root / "Results/paper_reproduction" / name).read_text()
        records = text.split("## Target records\n", 1)[1]
        rows = table_rows(records)[1:]  # Skip the column headings.
        header = table_rows(records)[0]
        outcomes = [row[header.index("outcome")].strip("`") for row in rows]
        automated = outcomes.count("accepted_final_checker")
        manual = outcomes.count("accepted_manual_final_checker")
        if not rows:
            raise ValueError("Empty target report")
        result.append((label, len(rows), automated, manual))
    return result


def text(x: float, y: float, value: str, cls: str = "", anchor: str = "start") -> str:
    return (f'  <text x="{x:g}" y="{y:g}" class="{cls}" '
            f'text-anchor="{anchor}">{escape(value)}</text>')


def rect(x: float, y: float, width: float, height: float, cls: str) -> str:
    return (f'  <rect x="{x:.3f}" y="{y:.3f}" width="{width:.3f}" '
            f'height="{height:.3f}" class="{cls}"/>')


def svg(title: str, description: str, height: int, body: list[str], defs: str = "") -> str:
    return "\n".join([
        '<svg xmlns="http://www.w3.org/2000/svg" width="640" '
        f'height="{height}" viewBox="0 0 640 {height}" role="img" '
        'aria-labelledby="title desc">',
        '  <!-- Generated by docs/build_results_charts.py; edit the source data. -->',
        f'  <title id="title">{escape(title)}</title>',
        f'  <desc id="desc">{escape(description)}</desc>',
        f'  <defs><style>{STYLE}  </style>{defs}</defs>',
        rect(0, 0, 640, height, "background"), *body, '</svg>', '',
    ])


def benchmark_chart(root: Path = ROOT) -> str:
    data = benchmark_data(root)
    body = [text(28, 38, "Benchmark performance", "heading"),
            text(28, 70, "Reported score (%) · GPT-5.5 xhigh"),
            rect(28, 94, 16, 16, "direct"), text(54, 109, "Direct model"),
            rect(250, 94, 16, 16, "pipeline"), text(276, 109, "S0–S6 pipeline")]
    bottom, plot_height = 340, 210
    for tick in (0, 50, 100):
        y = bottom - tick * plot_height / 100
        body += [f'  <path d="M76 {y:g}H612" class="grid"/>',
                 text(62, y + 7, str(tick), anchor="end")]
    descriptions = []
    for index, (name, direct, pipeline, difference) in enumerate(data):
        center = 208 + 280 * index
        for offset, value, cls in ((-92, direct, "direct"), (8, pipeline, "pipeline")):
            height = float(value.rstrip("%")) * plot_height / 100
            x = center + offset
            body += [rect(x, bottom - height, 84, height, cls),
                     text(x + 42, bottom - height - 12, value, "value", "middle")]
        body += [text(center, 377, name, "label", "middle"),
                 text(center, 408, difference.replace("percentage points", "pp"),
                      "value", "middle")]
        descriptions.append(f"{name}: direct model {direct}; S0–S6 pipeline {pipeline}; "
                            f"difference {difference}.")
    body += [text(28, 453, "Project-reported; runs not compute-matched.", "note"),
             text(28, 483, "pp = percentage points", "note")]
    return svg("Benchmark performance", " ".join(descriptions) +
               " Both groups use a zero-to-100-percent scale. Project-reported "
               "scores; direct and pipeline runs were not compute-matched.", 508, body)


def paper_chart(root: Path = ROOT) -> str:
    data = paper_data(root)
    same_total = len({row[1] for row in data}) == 1
    subtitle = (f"{data[0][1]} target statements per setup" if same_total
                else "Share of target statements in each setup")
    body = [text(28, 38, "Paper-proof reconstruction", "heading"),
            text(28, 70, subtitle),
            rect(28, 98, 16, 16, "pipeline"), text(54, 114, "Automated"),
            '<rect x="238" y="98" width="16" height="16" fill="url(#manual)"/>',
            text(264, 114, "Manual"),
            rect(386, 98, 16, 16, "other"), text(412, 114, "Other outcomes")]
    descriptions = []
    for index, (label, total, automated, manual) in enumerate(data):
        y = 180 + index * 126
        passed = automated + manual
        body += [text(28, y - 18, label, "label"),
                 text(612, y - 18, f"{passed}/{total} · {100 * passed / total:.1f}%",
                      "value", "end")]
        x = 28.0
        for count, cls in ((automated, "pipeline"), (manual, "manual"),
                           (total - passed, "other")):
            if count == 0:
                continue
            width = count * 584 / total
            if cls == "manual":
                body.append(f'  <rect x="{x:.3f}" y="{y}" width="{width:.3f}" '
                            'height="46" fill="url(#manual)"/>')
            else:
                body.append(rect(x, y, width, 46, cls))
            count_class = {"pipeline": "on-pass", "manual": "on-manual",
                           "other": "value"}[cls]
            body.append(text(x + width / 2, y + 31, str(count), count_class, "middle"))
            x += width
        descriptions.append(f"{label}: {automated} automated passes, {manual} manual "
                            f"passes, {total - passed} other outcomes; {passed}/{total} "
                            f"passed ({100 * passed / total:.1f}%).")
    body += [text(28, 396, "Final Checker passes; not formal verification.", "note"),
             text(28, 426, "Other outcomes include setup and runtime stops.", "note")]
    pattern = ('<pattern id="manual" width="8" height="8" patternUnits="userSpaceOnUse">'
               '<rect width="8" height="8" fill="#f2c66d"/>'
               '<path d="M-2 2L2 -2M0 8L8 0M6 10L10 6" '
               'stroke="#a56c13" stroke-opacity=".3" stroke-width="2"/></pattern>')
    return svg("Paper-proof reconstruction", " ".join(descriptions) +
               " Each paper–target pair is counted once, including setup failures. "
               "Passes are model-based Final Checker assessments, not formal proofs.",
               452, body, pattern)


def subject_metadata(root: Path = ROOT) -> dict:
    return json.loads((root / "Results/paper_reproduction/subjects.json").read_text())


def subject_counts(root: Path = ROOT) -> list[tuple[str, str, int]]:
    metadata = subject_metadata(root)
    papers = metadata["papers"]
    if not papers or len({paper["arxiv_id"] for paper in papers}) != len(papers):
        raise ValueError("Subject metadata must contain unique, nonempty paper records")
    counts = Counter(paper["primary_category"] for paper in papers)
    rows = [(code, metadata["category_names"][code], count)
            for code, count in counts.items()]
    return sorted(rows, key=lambda row: (-row[2], row[1]))


def subject_chart(root: Path = ROOT) -> str:
    rows = subject_counts(root)
    total = sum(row[2] for row in rows)
    maximum = max(row[2] for row in rows)
    top, row_height, left, plot_width = 108, 42, 330, 246
    bottom = top + row_height * len(rows)
    body = [text(28, 38, "Paper-reproduction subjects", "heading"),
            text(28, 70, f"{total} papers · {len(rows)} primary arXiv categories")]
    # Integer ticks with a zero baseline; direct labels show every exact count.
    ticks = sorted(set(range(0, maximum + 1, max(1, (maximum + 3) // 4))) | {maximum})
    for tick in ticks:
        x = left + tick * plot_width / maximum
        body += [f'  <path d="M{x:g} {top}V{bottom}" class="grid"/>',
                 text(x, bottom + 28, str(tick), anchor="middle")]
    for index, (_, name, count) in enumerate(rows):
        y = top + index * row_height
        width = count * plot_width / maximum
        body += [text(left - 20, y + 20, name, anchor="end"),
                 rect(left, y, width, 26, "coverage"),
                 text(left + width + 12, y + 20, str(count), "value")]
    body += [text(left + plot_width / 2, bottom + 63, "Number of papers", anchor="middle"),
             text(28, bottom + 96, "Each paper counted once; cross-lists excluded.", "note")]
    description = "; ".join(f"{name} ({code}): {count}" for code, name, count in rows)
    return svg("Paper-reproduction subjects", f"{total} unique papers. {description}. "
               "Counts use each paper's primary arXiv category, not cross-listings or "
               "individual target statements. This is coverage, not subject-level accuracy.",
               bottom + 122, body)


def subject_section(root: Path = ROOT, detailed: bool = True) -> str:
    metadata = subject_metadata(root)
    rows = subject_counts(root)
    papers = metadata["papers"]
    total = len(papers)
    image_path = "../../docs" if detailed else "../docs"
    lines = ["## Subject coverage", "",
             f"The paper-reproduction collection covers **{total} unique papers** across",
             f"**{len(rows)} primary arXiv categories**. These counts describe the collection,",
             "not subject-level accuracy.", "",
             "![Number of unique papers in each primary arXiv subject category.]"
             f"({image_path}/paper-subject-coverage.svg)", ""]
    if not detailed:
        lines += [f"[Explore all {total} papers and their subjects]"
                  "(paper_reproduction/README.md#subject-coverage).", ""]
        return "\n".join(lines)
    lines += ["<details>", f"<summary>Explore all {total} papers and their subjects</summary>", "",
              "| Paper | Title | Primary subject |", "|---|---|---|"]
    for paper in papers:
        paper_id = paper["arxiv_id"]
        # Normalize inline TeX delimiters for GitHub; retain original titles in JSON.
        title = paper["title"].replace(r"\(", "$").replace(r"\)", "$")
        title = title.replace("|", r"\|")
        category = paper["primary_category"]
        name = metadata["category_names"][category]
        lines.append(f"| [{paper_id}](https://arxiv.org/abs/{paper_id}) | "
                     f"{title} | {name} (`{category}`) |")
    lines += ["", f"Primary categories and current titles were checked on **{metadata['checked_on']}**",
              "using [arXiv metadata](https://info.arxiv.org/help/api/user-manual.html).",
              "Each paper is counted once, regardless of the number of tested targets or",
              "cross-listings. The [metadata snapshot](subjects.json) records the retrieved",
              "versions; these are not necessarily the versions used in the historical runs.",
              "", "</details>", ""]
    return "\n".join(lines)


def subject_readmes(root: Path = ROOT) -> dict[Path, str]:
    start, end = "<!-- BEGIN SUBJECT COVERAGE -->", "<!-- END SUBJECT COVERAGE -->"
    result = {}
    for relative, detailed in (("Results/README.md", False),
                               ("Results/paper_reproduction/README.md", True)):
        path = root / relative
        original = path.read_text()
        if original.count(start) != 1 or original.count(end) != 1:
            raise ValueError(f"Expected one subject-coverage block in {relative}")
        before, _, remaining = original.partition(start)
        _, _, after = remaining.partition(end)
        result[path] = before + start + "\n\n" + subject_section(root, detailed) + "\n" + end + after
    return result


def figures(root: Path = ROOT) -> dict[str, str]:
    return {"benchmark-results.svg": benchmark_chart(root),
            "paper-reproduction-results.svg": paper_chart(root),
            "paper-subject-coverage.svg": subject_chart(root)}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    rendered = figures()
    artifacts = {ROOT / "docs" / name: content for name, content in rendered.items()}
    artifacts.update(subject_readmes())
    for path, content in artifacts.items():
        if args.write:
            path.write_text(content, encoding="utf-8")
        elif not path.exists() or path.read_text(encoding="utf-8") != content:
            stale.append(str(path.relative_to(ROOT)))
    if stale:
        print("Stale result figures or subject lists: " + ", ".join(stale))
        print("Run python3 -B docs/build_results_charts.py --write")
        return 1
    print(f"Results figures current ({len(rendered)} files); subject lists current")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
